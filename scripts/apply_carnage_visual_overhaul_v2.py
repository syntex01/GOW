def update_faction_units() -> None:
    path = "src/data/factions.ts"
    source = read(path)
    for unit_id, variant in UNIT_VARIANTS.items():
        pattern = re.compile(
            rf"(id:\s*['\"]{re.escape(unit_id)}['\"][\s\S]*?visual:\s*\{{)([\s\S]*?)(\n\s*\}})"
        )
        match = pattern.search(source)
        if match is None or "variant:" in match.group(2):
            continue
        indentation_match = re.search(r"\n(\s*)\S", match.group(2))
        indentation = indentation_match.group(1) if indentation_match else "      "
        replacement = (
            match.group(1)
            + f"\n{indentation}variant: '{variant}',"
            + match.group(2)
            + match.group(3)
        )
        source = source[:match.start()] + replacement + source[match.end():]
    write(path, source)


FALLBACK_HELPER = """const CARNAGE_FALLBACK_VARIANT: Record<string, import('../gfx/carnageVisualVariants').CarnageVisualVariant> = {
  man_at_arms: 'corrupted-infantry',
  longbowman: 'corrupted-longbow',
  pikeman: 'corrupted-pike',
  knight: 'corrupted-knight',
  battle_monk: 'corrupted-monk',
  field_surgeon: 'corrupted-surgeon'
}

function fallbackCarnageVariant(base: UnitDef): import('../gfx/carnageVisualVariants').CarnageVisualVariant {
  const direct = CARNAGE_FALLBACK_VARIANT[base.id]
  if (direct) return direct
  const name = base.name.toLowerCase()
  if (name.includes('longbow')) return 'corrupted-longbow'
  if (name.includes('pike')) return 'corrupted-pike'
  if (name.includes('knight')) return 'corrupted-knight'
  if (name.includes('monk')) return 'corrupted-monk'
  if (name.includes('surgeon')) return 'corrupted-surgeon'
  return 'corrupted-infantry'
}

"""


def update_morphs() -> None:
    path = "src/data/morphs.ts"
    source = read(path)
    marker = "function carnageVisualFor("
    if "CARNAGE_FALLBACK_VARIANT" not in source:
        index = source.find(marker)
        if index < 0:
            raise RuntimeError("carnageVisualFor not found")
        source = source[:index] + FALLBACK_HELPER + source[index:]

    source = re.sub(
        r"(function\s+carnageVisualFor\s*\(base:\s*UnitDef\)[^{]*\{)(?!\s*\n\s*const variant)",
        r"\1\n  const variant = fallbackCarnageVariant(base)",
        source,
        count=1,
    )
    match = re.search(r"function\s+carnageVisualFor\s*\(base:\s*UnitDef\)[^{]*\{", source)
    if match is None:
        raise RuntimeError("carnageVisualFor missing after helper insertion")
    depth = 0
    end = None
    for index in range(match.end() - 1, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                end = index + 1
                break
    if end is None:
        raise RuntimeError("Could not find carnageVisualFor end")
    block = source[match.start():end]
    block = re.sub(r"return\s*\{(?!\s*variant)", "return { variant,", block)
    source = source[:match.start()] + block + source[end:]
    write(path, source)


