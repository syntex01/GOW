def update_types() -> None:
    path = "src/data/types.ts"
    source = read(path)
    if "CarnageVisualVariant" not in source:
        source = "import type { CarnageVisualVariant } from '../gfx/carnageVisualVariants'\n" + source
    if "variant?: CarnageVisualVariant" not in source:
        patterns = [r"(export\s+interface\s+UnitVisual\s*\{)", r"(export\s+type\s+UnitVisual\s*=\s*\{)"]
        for pattern in patterns:
            if re.search(pattern, source):
                source = re.sub(
                    pattern,
                    r"\1\n  /** Design-specific procedural silhouette for Carnage progression. */\n  variant?: CarnageVisualVariant",
                    source,
                    count=1,
                )
                break
        else:
            raise RuntimeError("UnitVisual declaration not found")
    write(path, source)


def update_dispatcher() -> None:
    path = "src/gfx/unitArt.ts"
    source = read(path)
    if "applyCarnageVisualVariant" not in source:
        lines = source.splitlines()
        last_import = max(index for index, line in enumerate(lines) if line.startswith("import "))
        lines.insert(last_import + 1, "import { applyCarnageVisualVariant } from './carnageVisualVariants'")
        source = "\n".join(lines) + "\n"

    if "applyCarnageVisualVariant(visual" not in source:
        starts = list(re.finditer(r"export\s+(?:default\s+)?function\s+\w+\s*\(([^)]*)\)[^{]*\{", source))
        chosen: tuple[int, int] | None = None
        for match in starts:
            if "visual" not in match.group(1):
                continue
            depth = 0
            end = None
            for index in range(match.end() - 1, len(source)):
                if source[index] == "{":
                    depth += 1
                elif source[index] == "}":
                    depth -= 1
                    if depth == 0:
                        end = index + 1
                        break
            if end is not None and ".kind" in source[match.start():end]:
                chosen = (match.start(), end)
                break
        if chosen is None:
            raise RuntimeError("Unit art dispatcher not found")
        start, end = chosen
        block = source[start:end]
        block = re.sub(
            r"\breturn\s+([^;\n]+);",
            lambda match: f"return applyCarnageVisualVariant(visual, {match.group(1)});",
            block,
        )
        source = source[:start] + block + source[end:]
    write(path, source)


