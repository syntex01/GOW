from __future__ import annotations

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def write(path: str, content: str) -> None:
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")


def shape_import() -> str:
    source = read("src/gfx/archetypes/carnageFoot.ts")
    imports = re.findall(r"import[\s\S]*?from\s+['\"][^'\"]+['\"]", source)
    result = next((item for item in imports if "rect" in item and "circle" in item), None)
    if result is None:
        raise RuntimeError("Could not locate the pixel-shape helper import")
    for name in ("Shape", "rect", "circle", "ellipse", "line"):
        if name not in result:
            result = re.sub(r"import\s*\{", f"import {{ {name},", result, count=1)
    return result


