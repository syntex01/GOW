function look(faction: FactionId, extra: Partial<UnitVisual>): UnitVisual {
  return {
    kind: 'humanoid',
    helmet: 'none',
    torso: 'bare',
    weapon: 'fist',
    ...PALETTE[faction],
    ...extra
  } as UnitVisual
}

