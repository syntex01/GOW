/** The five units an ascended army fields. */
export function factionRoster(id: FactionId): UnitDef[] {
  const prefix: Record<FactionId, string> = {
    nekrotics: 'nk_',
    cyborgs: 'cy_',
    dark_circle: 'dc_',
    cinder_host: 'ch_',
    hollow_bloom: 'hb_'
  }
  return FACTION_UNITS.filter(u => u.id.startsWith(prefix[id]) && !u.hidden)
}
