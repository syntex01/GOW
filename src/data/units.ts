export const UNITS_BY_ID: Record<string, UnitDef> = Object.fromEntries(UNITS.map(u => [u.id, u]))

export function unitsForAge(age: number): UnitDef[] {
  return UNITS.filter(u => u.age === age)
}

/** Every unit the given age has access to (current age only, Age-of-War style). */
export function rosterForAge(age: number): UnitDef[] {
  return unitsForAge(Math.max(0, Math.min(4, age)))
}
