/**
 * The combo codex.
 *
 * One hundred named plays — combinations of positioning, research, unit
 * placement and macro timing — each stated with what it beats and what beats
 * it. This is the game's strategic surface written down: every entry refers
 * to real, simulated mechanics (conducts, the damage matrix, lane spill,
 * creed ground rules, deeds, veterancy), so the codex can drive an in-game
 * reference screen and the balance harnesses can sample it for truth.
 *
 * The design rule behind every entry: nothing is strong without a stated
 * answer, and every answer is itself an entry with answers. The web has no
 * top — that is what "balanced" means here.
 */

export type ComboDomain = 'positioning' | 'tech' | 'placement' | 'macro'

export interface ComboEntry {
  id: string
  name: string
  domain: ComboDomain
  /** Unit ids, tech ids or mechanic names this play is built from. */
  pieces: string[]
  /** What you actually do. */
  play: string
  /**
   * What this play punishes — codex entry ids where an entry exists, plain
   * concept tags (e.g. 'attrition_grind', 'ranged_standoff') where the thing
   * being beaten is a posture rather than a named play.
   */
  beats: string[]
  /** What punishes this play. Same convention as `beats`. */
  counteredBy: string[]
}

